# ─────────────────────────────────────────────────────── inline formatting

def inline(text):
    """`code`, **bold**, *italic*, [links] — in that order, and code first.

    Code spans are lifted out before anything else touches them, or a snippet
    containing an asterisk gets turned into italics inside a code block.
    """
    spans = []

    def stash(match):
        spans.append(match.group(1))
        return f"\x00{len(spans) - 1}\x00"

    text = re.sub(r"`([^`]+)`", stash, text)
    text = html_module.escape(text, quote=False)
    text = re.sub(r"\[([^\]]+)\]\(([^)]+)\)", r'<a href="\2">\1</a>', text)
    # non-greedy, and NOT [^*]+ — bold often wraps an italic:
    #   **The walls were about the *vendor*, not the model**
    # A pattern that forbids inner asterisks leaves both markers on the page.
    text = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", text)
    text = re.sub(r"(?<![*\w])\*([^*\n]+)\*(?!\*)", r"<em>\1</em>", text)
    for index, code in enumerate(spans):
        text = text.replace(f"\x00{index}\x00",
                            f"<code>{html_module.escape(code, quote=False)}</code>")
    return text


def slug(text):
    return re.sub(r"[^a-z0-9]+", "-", re.sub(r"<[^>]+>", "", text).lower()).strip("-")


# ─────────────────────────────────────────────────────── block rendering

def render(markdown):
    out, lines, i = [], markdown.replace("\r\n", "\n").split("\n"), 0
    open_list = None

    def close_list():
        nonlocal open_list
        if open_list:
            out.append(f"</{open_list}>")
            open_list = None

    while i < len(lines):
        line = lines[i]

        if line.startswith("```"):                              # fenced code
            close_list()
            language = line[3:].strip()
            body, i = [], i + 1
            while i < len(lines) and not lines[i].startswith("```"):
                body.append(lines[i]); i += 1
            i += 1
            css = f' class="lang-{slug(language)}"' if language else ""
            out.append(f"<pre><code{css}>"
                       + html_module.escape("\n".join(body), quote=False) + "</code></pre>")
            continue

        if re.fullmatch(r"\s*(-{3,}|\*{3,}|_{3,})\s*", line):    # horizontal rule
            close_list(); out.append("<hr>"); i += 1; continue

        heading = re.match(r"^(#{1,6})\s+(.*)$", line)
        if heading:
            close_list()
            level, text = len(heading.group(1)), inline(heading.group(2).strip())
            out.append(f'<h{level} id="{slug(text)}">{text}</h{level}>')
            i += 1; continue

        if line.lstrip().startswith("|") and i + 1 < len(lines) \
                and re.fullmatch(r"\s*\|[\s:|-]+\|\s*", lines[i + 1]):
            close_list()
            def cells(row):
                return [c.strip() for c in row.strip().strip("|").split("|")]
            header = cells(line); i += 2
            out.append("<table><thead><tr>"
                       + "".join(f"<th>{inline(c)}</th>" for c in header)
                       + "</tr></thead><tbody>")
            while i < len(lines) and lines[i].lstrip().startswith("|"):
                out.append("<tr>" + "".join(f"<td>{inline(c)}</td>"
                                            for c in cells(lines[i])) + "</tr>")
                i += 1
            out.append("</tbody></table>"); continue

        if line.startswith(">"):                                 # blockquote
            close_list()
            body = []
            while i < len(lines) and lines[i].startswith(">"):
                body.append(lines[i][1:].lstrip()); i += 1
            out.append("<blockquote>" + inline(" ".join(body)) + "</blockquote>")
            continue

        item = re.match(r"^(\s*)([-*+]|\d+[.)])\s+(.*)$", line)
        if item:
            wanted = "ol" if item.group(2)[0].isdigit() else "ul"
            if open_list != wanted:
                close_list(); out.append(f"<{wanted}>"); open_list = wanted
            body = [item.group(3)]
            i += 1
            while i < len(lines) and lines[i].strip() \
                    and not re.match(r"^(\s*)([-*+]|\d+[.)])\s+", lines[i]) \
                    and not lines[i].startswith(("#", "|", "```", ">")):
                body.append(lines[i].strip()); i += 1
            out.append(f"<li>{inline(' '.join(body))}</li>")
            continue

        if not line.strip():
            close_list(); i += 1; continue

        close_list()                                             # paragraph
        body = [line]
        i += 1
        while i < len(lines) and lines[i].strip() \
                and not lines[i].startswith(("#", "|", "```", ">", "---")) \
                and not re.match(r"^(\s*)([-*+]|\d+[.)])\s+", lines[i]):
            body.append(lines[i]); i += 1
        out.append("<p>" + inline(" ".join(body)) + "</p>")

    close_list()
    return "\n".join(out)


