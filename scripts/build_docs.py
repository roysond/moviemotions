def page(source, body, title):
    return f"""{BANNER.format(source=source)}
<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{html_module.escape(title)}</title>
<style>{STYLE}</style>
</head>
<body>
<div class="wrap">
<div class="stamp">MovieMotions · generated from {html_module.escape(source)}</div>
{body}
</div>
</body>
</html>
"""


def build(source):
    text = open(source, encoding="utf-8").read()
    first = re.search(r"^#\s+(.*)$", text, re.M)
    title = first.group(1).strip() if first else os.path.basename(source)
    return page(source, render(text), title)


def main():
    checking = "--check" in sys.argv
    stale, written = [], []
    for source, target in PAGES:
        if not os.path.exists(source):
            print(f"  ! {source} is missing — skipped")
            continue
        fresh = build(source)
        current = open(target, encoding="utf-8").read() if os.path.exists(target) else None
        if checking:
            if current != fresh:
                stale.append(target)
        elif current != fresh:
            open(target, "w", encoding="utf-8").write(fresh)
            written.append(target)

    if checking:
        if stale:
            print("OUT OF DATE — the markdown changed and the HTML was not rebuilt:")
            for target in stale:
                print(f"    {target}")
            print("\nRun:  python -m scripts.build_docs")
            return 1
        print(f"all {len(PAGES)} generated pages are up to date")
        return 0

    print(f"rebuilt {len(written)} of {len(PAGES)} pages"
          + ("".join(f"\n    {t}" for t in written) if written else " (nothing changed)"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
