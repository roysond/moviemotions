"""
build_docs.py — render the markdown docs to HTML, so there is ONE source.

THE PROBLEM THIS EXISTS TO KILL
    docs/ held HTML copies of the markdown, kept in step by hand. On 30 Aug 2026 the
    markdown described four agent tools, a semantic layer, a React front end and 37
    tests; the HTML still described a system from ten days earlier. Nobody lied — the
    second copy simply drifted, the way second copies do.

    Same failure as REGION being defined in two files, and as the test environment
    being typed out instead of read from the code. A fact written down twice will
    eventually disagree with itself.

    So the markdown is the source and the HTML is derived — like the knowledge graph
    from raw_payload, or static/ from frontend/. Derived files are disposable and are
    never edited by hand.

WHAT IS **NOT** GENERATED
    The six diagram pages — ARCHITECTURE, CONCEPT-MAP, PASS-0/1/2-DIAGRAM, PASS-GROWTH —
    have no markdown source. They are drawings, not prose, and stay hand-built. They
    are not duplicates of anything, so they cannot drift in this way.

RUN IT
    python -m scripts.build_docs            write the HTML
    python -m scripts.build_docs --check    fail if a page is out of date (CI runs this)

Standard library only, on purpose. A gate that needs a dependency install can be
broken BY a dependency — the same rule repo_check.py follows.
"""

